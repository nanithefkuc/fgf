def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST,
                        help="committed session manifest")
    parser.add_argument("--records", type=Path, default=DEFAULT_RECORDS,
                        help="root holding the published session directories")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="root for BENCHMARKS.md and benchmarks/")
    parser.add_argument("--verify", action="store_true",
                        help="regenerate and compare bytes without writing")
    arguments = parser.parse_args(argv)

    try:
        hosts, sessions, competitors, metadata = load_manifest(
            arguments.manifest, arguments.records)
        pages = generate(hosts, sessions, competitors, metadata)
    except PublishError as exc:
        print(f"publish: {exc}", file=sys.stderr)
        return 2 if arguments.verify else 1

    if arguments.verify:
        mismatches = []
        for relative, content in sorted(pages.items()):
            path = arguments.output / relative
            if not path.is_file():
                mismatches.append(f"missing {path}")
            elif path.read_bytes() != content:
                mismatches.append(f"changed {path}")
        if mismatches:
            for line in mismatches:
                print(f"publish: verify: {line}", file=sys.stderr)
            return 2
        print(f"verified {len(pages)} pages and {len(sessions)} session digests")
        return 0

    for relative, content in sorted(pages.items()):
        path = arguments.output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    print(f"wrote {len(pages)} pages under {arguments.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
