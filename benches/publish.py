def _md(value: Any) -> str:
    text = "-" if value is None or value == "" else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown_table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |",
           "| " + " | ".join(["---"] * len(header)) + " |"]
    for row in rows:
        out.append("| " + " | ".join(_md(cell) for cell in row) + " |")
    return "\n".join(out)


def _digits_for(rows: list[PublishedRow]) -> int | None:
    values = [value for row in rows
              for value in (row.summary_ns, row.data.get("min_ns"), row.data.get("max_ns"))
              if value is not None]
    return table_digits(values) if values else None


def _measurement_record(row: PublishedRow) -> str:
    session = row.session.data
    if session.get("method_version") in STAGED_METHODS:
        decision = ((session.get("decisions") or {}).get("per_tier") or {}).get(row.tier, {})
        noninferiority = decision.get("noninferiority") or {}
        if row.cell in noninferiority.get("confirmed_failures", []):
            return "confirmed_regression"
        if row.cell in noninferiority.get("unconfirmed_failures", []):
            return "unconfirmed_main_failure"
    if row.arm == "layout_control":
        return "layout_control"
    return "descriptive" if session["kind"] == "descriptive" else "accepted"


def _measurement_table(rows: list[PublishedRow], host_index: HostIndex,
                       *, current: bool) -> str:
    digits = _digits_for(rows)
    header = ["Host", "Tier", "Cell", "Arm", "Record", "Scope", "Runs × rounds",
              "Library SHA", "Session", "Unstable", "ns/call",
              "Minimum (ns/call)", "Maximum (ns/call)"]
    lines = []
    for row in rows:
        host = host_index.name(row.host)
        if current:
            anchor = html.escape(row.anchor, quote=True)
            host = f'<a id="{anchor}"></a>{host}'
        else:
            target = ("../BENCHMARKS.md" if row.session.data["snapshot"].get("bench", "operations") == "operations"
                      else "surfaces.md")
            host = f"[{host}]({target}#{row.anchor})"
        value = "-" if digits is None else fmt_value(row.summary_ns, digits)
        session = row.session.data
        scope = session.get("scope") or {"kind": "full"}
        scope_label = scope["kind"]
        if scope_label == "selected":
            scope_label += f" {len(scope['cells'])}"
        record = _measurement_record(row)
        minimum = row.data.get("min_ns")
        maximum = row.data.get("max_ns")
        lines.append([host, row.tier, f"`{row.cell}`", row.arm, record, scope_label,
                      f"{session['config']['runs']} × {session['config']['rounds']}",
                      f"`{row.data['library_sha']}`", f"`{row.session.data['session_id']}`",
                      "yes" if row.data["unstable"] else "-", value,
                      "-" if minimum is None else fmt_value(minimum, digits),
                      "-" if maximum is None else fmt_value(maximum, digits)])
    return render_markdown_table(header, lines)


def _host_facts(sessions: list[PublishedSession], kinds: tuple[str, ...] = KINDS) -> dict[str, dict]:
    facts: dict[str, dict] = {}
    for session in sessions:
        if session.data["kind"] not in kinds:
            continue
        host = session.data["host"]
        facts[host["hostname"]] = host
    return facts


def _host_table(hosts: list[HostSpec], sessions: list[PublishedSession],
                kinds: tuple[str, ...]) -> str:
    facts = _host_facts(sessions, kinds)
    counts: dict[str, int] = {}
    for session in sessions:
        if session.data["kind"] not in kinds:
            continue
        for host in {row["host"] for row in session.data["rows"]}:
            counts[host] = counts.get(host, 0) + 1
    lines = []
    for spec in hosts:
        fact = next((facts[key] for key in spec.keys if key in facts), None)
        available = "yes" if spec.available else "no"
        if not spec.available:
            lines.append([spec.name, available, "-", "-", "-", "-"])
            continue
        count = sum(counts.get(key, 0) for key in spec.keys)
        lines.append([
            spec.name,
            available,
            "-" if fact is None else fact["cpu_model"],
            "-" if fact is None else fact["os"],
            "-" if fact is None else fact["pinned_core"],
            "-" if not count else str(count),
        ])
    header = ["Host", "Available", "CPU", "OS", "Pinned core", "Sessions"]
    return render_markdown_table(header, lines)


