def render_calibration(hosts: list[HostSpec], sessions: list[PublishedSession],
                       host_index: HostIndex, rows: list[PublishedRow],
                       tiers: list[str]) -> str:
    ordered = _ordered_rows(rows, host_index, tiers, history=True)
    digits = _digits_for(ordered)
    measurements = []
    for row in ordered:
        mode = row.session.data["calibration"]["mode"]
        value = "-" if digits is None else fmt_value(row.summary_ns, digits)
        measurements.append([
            host_index.name(row.host), row.tier, f"`{row.cell}`", row.arm,
            f"`{row.data['library_sha']}`",
            f"`{row.session.data['session_id']}`",
            "yes" if row.data["unstable"] else "-", mode, value,
        ])
    summaries = []
    for session in sessions:
        if session.data["kind"] != "calibration":
            continue
        calibration = session.data["calibration"]
        recommendation = calibration["recommendation"]
        for tier, tier_record in recommendation["per_tier"].items():
            runs = tier_record.get("runs")
            summaries.append([
                f"`{session.data['session_id']}`",
                calibration["mode"],
                tier,
                "-" if runs is None else str(runs),
                fmt_ratio(float(recommendation["drift_cap"])),
                fmt_ratio(tier_record.get("max_bound")),
                fmt_ratio(tier_record.get("limit")),
                str(len(tier_record.get("unstable_cells") or [])),
            ])
    lines = [
        "# Calibration sessions",
        "",
        "## Measurements",
        "",
        render_markdown_table(
            ["Host", "Tier", "Cell", "Arm", "Library SHA", "Session",
             "Unstable", "Mode", "ns/call"], measurements),
        "",
        "## Recommendations",
        "",
        render_markdown_table(
            ["Session", "Mode", "Tier", "Recommended runs", "Drift cap",
             "Max bound", "Limit", "Unstable cells"], summaries),
    ]
    _append_caveats(lines, hosts)
    return "\n".join(lines).rstrip() + "\n"


def render_thresholds(hosts: list[HostSpec], sessions: list[PublishedSession],
                      host_index: HostIndex, rows: list[PublishedRow],
                      tiers: list[str]) -> str:
    ordered = _ordered_rows(rows, host_index, tiers, history=True)
    digits = _digits_for(ordered)
    staged = any(row.session.data["method_version"] in STAGED_METHODS for row in ordered)
    measurements = []
    for row in ordered:
        value = "-" if digits is None else fmt_value(row.summary_ns, digits)
        measurements.append([
            host_index.name(row.host), row.tier, f"`{row.cell}`", row.arm,
            *([_measurement_record(row)] if staged else []),
            f"`{row.data['library_sha']}`",
            f"`{row.session.data['session_id']}`",
            "yes" if row.data["unstable"] else "-", value,
        ])
    lines = [
        "# Threshold evidence",
        "",
        "## Measurements",
        "",
        render_markdown_table(
            ["Host", "Tier", "Cell", "Arm", *(["Record"] if staged else []),
             "Library SHA", "Session", "Unstable", "ns/call"],
            measurements),
    ]
    by_unit: dict[str, list[PublishedSession]] = {}
    for session in sessions:
        if session.data["kind"] != "threshold":
            continue
        threshold = session.data["threshold"]
        by_unit.setdefault(threshold["unit"], []).append(session)
    for unit in UNITS:
        group = by_unit.get(unit)
        if not group:
            continue
        values = []
        for session in group:
            threshold = session.data["threshold"]
            values += [float(threshold["old"]), float(threshold["new"])]
        positive = [value for value in values if value > 0.0]
        digits = table_digits(positive) if positive else 3
        declarations = []
        for session in group:
            threshold = session.data["threshold"]
            old = fmt_cutoff(float(threshold["old"]), digits)
            new = fmt_cutoff(float(threshold["new"]), digits)
            declarations.append([
                f"`{session.data['session_id']}`",
                f"`{threshold['item_key']}`",
                old,
                new,
                str(len(threshold["cells"])),
                str(len(threshold["target_set"])),
            ])
        lines += [
            "",
            f"## Declarations ({unit})",
            "",
            render_markdown_table(
                ["Session", "Item", f"Old cutoff ({unit})",
                 f"New cutoff ({unit})", "Declared cells", "Target cells"],
                declarations),
        ]
    _append_caveats(lines, hosts)
    return "\n".join(lines).rstrip() + "\n"


