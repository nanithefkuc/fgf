        "candidates are labelled `layout_control`.",
        "- Aggregation: each row reports the arm's session summary, computed "
        "as the median of its per-run summaries; each run summary is the median "
        "of that run's per-round inner-batch medians.",
        "- Setup, allocation, coefficient construction, and input generation "
        "stay outside the timed region; inputs are warmed before each timed batch.",
        "- Every cell is checked against the independent element-wise oracle "
        "before timing.",
        f"- Snapshots pin 64-byte function and loop alignment with {flags}.",
        "- Descriptive records measure one revision without an acceptance claim. "
        "Minimum and maximum describe the range across standalone run summaries, "
        "not a confidence interval.",
        "- Latest measurements retain their measured revision, session, and harness "
        "snapshot. Rows from different sessions are not matched comparisons or "
        "proof of the newest release's performance.",
        "- Speedup, regression, crossover, and competitor claims use matched "
