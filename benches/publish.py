def anchor_for(row: dict, harness: str = "operations") -> str:
    prefix = "" if harness == "operations" else f"{harness}/"
    return f"{prefix}{row['host']}/{row['tier']}/{row['cell']}"


def _cell_key(row: dict) -> tuple:
    return (row["field"], row["operation"], row["prep"], row["row_len"],
            row["rows"], row["sources"], row["alignment"])


def _row_label(session: dict, row: dict) -> str | None:
    """Which arm of a paired session belongs in the published table."""
    if session["kind"] == "descriptive":
        return "descriptive"
    arms = session["arms"]
    same_sha = arms["base"]["sha"] == arms["candidate"]["sha"]
    candidate_kind = arms["candidate"].get("kind")
    if session["kind"] == "calibration":
        mode = (session.get("calibration") or {}).get("mode")
        if mode == "base_vs_layout_control":
            return "layout_control" if row["arm"] == "candidate" else "baseline"
        return "baseline" if row["arm"] == "candidate" else None
    if row["arm"] != "candidate":
        return None
    if candidate_kind == "layout_control":
        return "layout_control"
    return "baseline" if same_sha else "candidate"


def _collect_rows(sessions: list[PublishedSession], kind: str) -> list[PublishedRow]:
    rows: list[PublishedRow] = []
    for session in sessions:
        if session.data["kind"] != kind:
            continue
        if kind == "acceptance" and _is_exception_session(session.data):
            continue
        for row in session.data["rows"]:
            label = _row_label(session.data, row)
            if label is None:
                continue
            rows.append(PublishedRow(
                session=session,
                data=row,
                anchor=anchor_for(row, session.data["snapshot"].get("bench", "operations")),
                host=row["host"],
                tier=row["tier"],
                cell=row["cell"],
                cell_key=_cell_key(row),
                arm=label,
                summary_ns=float(row["summary_ns"]),
            ))
    return rows


class HostIndex:
    def __init__(self, hosts: list[HostSpec], rows: list[PublishedRow]):
        self.specs = list(hosts)
        self.by_key: dict[str, int] = {}
        for index, spec in enumerate(self.specs):
            for key in spec.keys:
                self.by_key[key] = index
        for row in rows:
            if row.host not in self.by_key:
                fail(f"host {row.host!r} is not declared in manifest metadata")
            if not self.specs[self.by_key[row.host]].available:
                fail(f"unavailable host {row.host!r} has published rows")

    def name(self, host: str) -> str:
        index = self.by_key.get(host)
        return host if index is None else self.specs[index].name

    def rank(self, host: str) -> int:
        return self.by_key.get(host, len(self.specs))


def _tier_rank(tiers: list[str], tier: str) -> int:
    try:
        return tiers.index(tier)
    except ValueError:
        return len(tiers)


def _tier_order(hosts_metadata: dict | None) -> list[str]:
    declared = TIER_ORDER
    if hosts_metadata is not None:
        tiers = hosts_metadata.get("tiers")
        if tiers is not None:
            if not isinstance(tiers, list) or not all(isinstance(t, str) for t in tiers):
                fail("manifest.metadata.tiers must be a list of strings")
            declared = tuple(tiers)
    return list(declared)


def _row_sort_key(row: PublishedRow, host_index: HostIndex,
                  tiers: list[str], session_order: int | None = None) -> tuple:
    key = (
        host_index.rank(row.host),
        _tier_rank(tiers, row.tier),
        row.cell_key,
        LABEL_ORDER.index(row.arm) if row.arm in LABEL_ORDER else len(LABEL_ORDER),
    )
    if session_order is None:
        return key
    return (session_order, *key)


def _ordered_rows(rows: list[PublishedRow], host_index: HostIndex,
                  tiers: list[str], *, history: bool) -> list[PublishedRow]:
    if history:
        return sorted(rows, key=lambda row: _row_sort_key(
            row, host_index, tiers, row.session.order))
    return sorted(rows, key=lambda row: _row_sort_key(row, host_index, tiers))


def _current_rows(rows: list[PublishedRow], host_index: HostIndex,
                  tiers: list[str]) -> list[PublishedRow]:
    latest: dict[str, PublishedRow] = {}
    for row in _ordered_rows(rows, host_index, tiers, history=True):
        latest[row.anchor] = row
    return _ordered_rows(list(latest.values()), host_index, tiers, history=False)


