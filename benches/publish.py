GIB = 1024.0 ** 3


def _record_number(value: str, where: str) -> float:
    try:
        number = float(value)
    except ValueError:
        fail(f"{where} is not a number: {value!r}")
    if not math.isfinite(number):
        fail(f"{where} is not finite: {value!r}")
    return number


def _gib_per_second(bytes_: int, ns: float, where: str) -> float:
    if bytes_ < 0 or ns <= 0.0:
        fail(f"{where} has no positive throughput")
    return bytes_ / (ns / 1e9) / GIB


def _parse_competitor_log(text: str, where: str) -> tuple[CompetitorTable, ...]:
    trio_order: list[tuple] = []
    trio: dict[tuple, dict] = {}
    prime_order: dict[str, list[tuple]] = {"rate": [], "scalar": []}
    prime: dict[str, dict[tuple, dict]] = {"rate": {}, "scalar": {}}
    gf16_order: list[tuple] = []
    gf16_arms: list[str] = []
    gf16: dict[tuple, dict] = {}

    def tally(store: dict, order: list, key: tuple, labels: tuple,
              arm: str, value: float) -> None:
        entry = store.get(key)
        if entry is None:
            entry = {"labels": labels, "values": {}}
            store[key] = entry
            order.append(key)
        entry["values"].setdefault(arm, []).append(value)

    for line in text.splitlines():
        if not line:
            continue
        parts = line.split("\t")
        tag = parts[0]
        if tag == "TRIO":
            if len(parts) != 10:
                fail(f"{where} has a malformed TRIO record")
            label = parts[1]
            try:
                bytes_ = int(parts[2])
            except ValueError:
                fail(f"{where} has a malformed TRIO byte count")
            key = (label, bytes_)
            labels = (label, str(bytes_))
            for arm, column in (("fgf", 3), ("ISA-L", 4), ("klauspost", 5)):
                tally(trio, trio_order, key, labels, arm,
                      _gib_per_second(bytes_, _record_number(parts[column], where),
                                      where))
        elif tag == "PRIME":
            if len(parts) != 8:
                fail(f"{where} has a malformed PRIME record")
            label = parts[1]
            kind = parts[2]
            try:
                bytes_ = int(parts[3])
            except ValueError:
                fail(f"{where} has a malformed PRIME byte count")
            ours = _record_number(parts[4], where)
            theirs = _record_number(parts[5], where)
            if kind == "rate":
                key = (label, bytes_)
                labels = (label, str(bytes_))
                for arm, value in (("fgf", _gib_per_second(bytes_, ours, where)),
                                   ("Plonky3",
                                    _gib_per_second(bytes_, theirs, where))):
                    tally(prime["rate"], prime_order["rate"], key, labels,
                          arm, value)
            elif kind == "scalar":
                key = (label,)
                labels = (label,)
                tally(prime["scalar"], prime_order["scalar"], key, labels,
                      "fgf", ours)
                tally(prime["scalar"], prime_order["scalar"], key, labels,
                      "Plonky3", theirs)
            else:
                fail(f"{where} has an unknown PRIME kind {kind!r}")
        elif tag == "RESULT":
            if len(parts) != 12:
                fail(f"{where} has a malformed RESULT record")
            label = parts[1]
            sources = parts[2]
            destinations = parts[3]
            try:
                bytes_ = int(parts[4])
            except ValueError:
                fail(f"{where} has a malformed RESULT byte count")
            schedule = parts[5]
            arm = parts[6]
            value = _record_number(parts[8], where)
            key = (label, sources, destinations, bytes_, schedule)
            tally(gf16, gf16_order, key,
                  (label, f"{sources} x {destinations}", schedule, str(bytes_)),
                  arm, value)
            if arm not in gf16_arms:
                gf16_arms.append(arm)

    def aggregated(store: dict, order: list, arms: tuple[str, ...],
                   label_headers: tuple[str, ...], title: str,
                   unit: str) -> CompetitorTable:
        rows = []
        for key in order:
            entry = store[key]
            values = tuple(
                statistics.median(entry["values"][arm])
                if arm in entry["values"] else None
                for arm in arms
            )
            rows.append(CompetitorRow(entry["labels"], values))
        return CompetitorTable(title, label_headers, arms, unit, tuple(rows))

    tables = []
    if trio:
        tables.append(aggregated(
            trio, trio_order, ("fgf", "ISA-L", "klauspost"),
            ("Shape", "Bytes"), "Trio", "GiB/s"))
    if prime["rate"]:
        tables.append(aggregated(
            prime["rate"], prime_order["rate"], ("fgf", "Plonky3"),
            ("Shape", "Bytes"), "Plonky3 rate", "GiB/s"))
    if prime["scalar"]:
        tables.append(aggregated(
            prime["scalar"], prime_order["scalar"], ("fgf", "Plonky3"),
            ("Shape",), "Plonky3 scalar", "ns/op"))
    if gf16:
        tables.append(aggregated(
            gf16, gf16_order, tuple(gf16_arms),
            ("Shape", "Sources x destinations", "Coefficients", "Bytes"),
            "GF16", "GiB/s"))
    if not tables:
        fail(f"{where} has no competitor records")
    return tuple(tables)


def _resolve_record_file(relative: str, records_root: Path, where: str) -> Path:
    path = Path(relative)
    if path.is_absolute():
        fail(f"{where}.path must be relative to the records root")
    if ".." in path.parts:
        fail(f"{where}.path must not leave the records root")
    full = records_root / path
    if not full.is_file():
        fail(f"{where}.path does not name a competitor log: {full}")
    return full


def _load_competitors(items: Any, records_root: Path,
                      hosts: list[HostSpec]) -> list[CompetitorLog]:
    if items is None:
        return []
    if not isinstance(items, list):
        fail("manifest.competitors must be a list")
    host_keys = {key: spec for spec in hosts for key in spec.keys}
    logs = []
    seen: set[Path] = set()
    for index, item in enumerate(items):
        where = f"manifest.competitors[{index}]"
        entry = _require_mapping(item, where)
        relative = _require_string(entry.get("path"), f"{where}.path")
        host = _require_string(entry.get("host"), f"{where}.host")
        spec = host_keys.get(host)
        if spec is None:
            fail(f"{where}.host {host!r} is not declared in manifest metadata")
        if not spec.available:
            fail(f"{where}.host {host!r} is marked unavailable")
        tier = _require_string(entry.get("tier"), f"{where}.tier")
        digest = entry.get("sha256", entry.get("digest"))
        digest = _require_string(digest, f"{where}.sha256").lower()
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            fail(f"{where}.sha256 must be 64 hex digits")
        path = _resolve_record_file(relative, records_root, where)
        resolved = path.resolve()
        if resolved in seen:
            fail(f"{where}.path repeats {relative!r}")
        seen.add(resolved)
        try:
            content = path.read_bytes()
        except OSError as exc:
            fail(f"cannot read {path}: {exc}")
        actual = hashlib.sha256(content).hexdigest()
        if actual != digest:
            fail(f"manifest digest mismatch for {relative}: expected {digest}, got {actual}")
        try:
            text = content.decode("utf-8")
        except UnicodeDecodeError as exc:
            fail(f"cannot read {path}: {exc}")
        label = entry.get("label")
        if label is None:
            label = Path(relative).stem
        label = _require_string(label, f"{where}.label")
        library_sha = entry.get("library_sha")
        if library_sha is not None:
            library_sha = _require_string(library_sha, f"{where}.library_sha")
        session_id = entry.get("session_id")
        if session_id is not None:
            session_id = _require_string(session_id, f"{where}.session_id")
        logs.append(CompetitorLog(
            relative=relative,
            digest=digest,
            host=host,
            tier=tier,
            label=label,
            library_sha=library_sha,
            session_id=session_id,
            tables=_parse_competitor_log(text, f"competitor {relative}"),
        ))
    return logs


def load_manifest(manifest_path: Path, records_root: Path) -> tuple[
        list[HostSpec], list[PublishedSession], list[CompetitorLog], dict]:
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"manifest not found: {manifest_path}")
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot read manifest {manifest_path}: {exc}")
    _require_mapping(manifest, "manifest")
    metadata = _require_mapping(manifest.get("metadata"), "manifest.metadata")
    host_items = metadata.get("hosts")
    if not isinstance(host_items, list) or not host_items:
        fail("manifest.metadata.hosts must be a non-empty list")
    hosts: list[HostSpec] = []
    seen: set[str] = set()
    for index, item in enumerate(host_items):
        where = f"manifest.metadata.hosts[{index}]"
        entry = _require_mapping(item, where)
        if "available" not in entry:
            fail(f"{where}.available must mark host availability")
        available = _require_bool(entry["available"], f"{where}.available")
        name = entry.get("name")
        if name is None:
            name = entry.get("host")
        name = _require_string(name, f"{where}.name")
        keys = []
        for key in ("host", "id", "hostname"):
            if key in entry:
                keys.append(_require_string(entry[key], f"{where}.{key}"))
        aliases = entry.get("aliases", [])
        if not isinstance(aliases, list):
            fail(f"{where}.aliases must be a list")
        for alias in aliases:
            keys.append(_require_string(alias, f"{where}.aliases[]"))
        if not keys:
            keys.append(name)
        for key in keys:
            if key in seen:
                fail(f"{where} repeats the host key {key!r}")
            seen.add(key)
        hosts.append(HostSpec(frozenset(keys), name, available))

    session_items = manifest.get("sessions")
    if not isinstance(session_items, list):
        fail("manifest.sessions must be a list")
    sessions: list[PublishedSession] = []
    seen_paths: set[Path] = set()
    configurations: dict[str, tuple] = {}
    seen_ids: set[str] = set()
    for index, item in enumerate(session_items):
        where = f"manifest.sessions[{index}]"
        entry = _require_mapping(item, where)
        relative = _require_string(entry.get("path"), f"{where}.path")
        digest = entry.get("sha256", entry.get("digest"))
        digest = _require_string(digest, f"{where}.sha256").lower()
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            fail(f"{where}.sha256 must be 64 hex digits")
        path = _resolve_relative(relative, records_root, where)
        resolved = path.resolve()
        if resolved in seen_paths:
            fail(f"{where}.path repeats {relative!r}")
        seen_paths.add(resolved)
        try:
            content = path.read_bytes()
        except OSError as exc:
            fail(f"cannot read {path}: {exc}")
        actual = hashlib.sha256(content).hexdigest()
        if actual != digest:
            fail(f"manifest digest mismatch for {relative}: expected {digest}, got {actual}")
        try:
            session = json.loads(content.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            fail(f"cannot read {path}: {exc}")
        validate_session(session, f"session {relative}")
        session_id = session["session_id"]
        if session_id in seen_ids:
            fail(f"{where} repeats session_id {session_id!r}")
        seen_ids.add(session_id)
        if path.parent.name != session_id:
            fail(f"session {relative} has session_id {session_id!r} "
                 f"but its directory is {path.parent.name!r}")
        if "kind" in entry and entry["kind"] != session["kind"]:
            fail(f"{where}.kind disagrees with the session")
        harness = session["snapshot"].get("bench", "operations")
        configuration = (tuple(sorted(session["snapshot"]["features"])),
                         " ".join(session["snapshot"]["rustflags"].split()),
                         bool(session["snapshot"].get("no_default_features", False)))
        if harness in configurations and configurations[harness] != configuration:
            fail(f"{where} mixes feature sets or flags within the {harness} record")
        configurations[harness] = configuration
        sessions.append(PublishedSession(relative, path, digest, session, index))
    competitors = _load_competitors(
        manifest.get("competitors", []), records_root, hosts)
    return hosts, sessions, competitors, metadata


