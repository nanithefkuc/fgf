def render_competitors(hosts: list[HostSpec],
                       competitors: list[CompetitorLog],
                       tiers: list[str]) -> str:
    host_rank: dict[str, int] = {}
    host_name: dict[str, str] = {}
    for index, spec in enumerate(hosts):
        for key in spec.keys:
            host_rank[key] = index
            host_name[key] = spec.name
    ordered = sorted(competitors, key=lambda log: (
        host_rank.get(log.host, len(hosts)),
        _tier_rank(tiers, log.tier),
        log.relative,
    ))
    lines = ["# Competitor measurements", ""]
    for log in ordered:
        lines += [f"## {host_name.get(log.host, log.host)} / {log.tier} / {log.label}",
                  ""]
        provenance = []
        if log.library_sha:
            provenance.append(f"Library SHA `{log.library_sha}`")
        if log.session_id:
            provenance.append(f"session `{log.session_id}`")
        if provenance:
            lines += [", ".join(provenance), ""]
        for table in log.tables:
            values = [value for row in table.rows for value in row.values
                      if value is not None]
            digits = table_digits(values) if values else None
            header = list(table.label_headers) + [
                f"{arm} ({table.unit})" for arm in table.arms]
            rows = []
            for row in table.rows:
                cells = list(row.labels)
                cells += ["-" if value is None or digits is None
                          else fmt_value(value, digits) for value in row.values]
                rows.append(cells)
            lines += [f"### {table.title}", "",
                      render_markdown_table(header, rows), ""]
    lines += ["## Caveats", ""]
    lines += _competitor_caveats(hosts)
    return "\n".join(lines).rstrip() + "\n"


def generate(hosts: list[HostSpec], sessions: list[PublishedSession],
             competitors: list[CompetitorLog], metadata: dict) -> dict[str, bytes]:
    acceptance = _collect_rows(sessions, "acceptance")
    calibration = _collect_rows(sessions, "calibration")
    threshold = _collect_rows(sessions, "threshold")
    descriptive = _collect_rows(sessions, "descriptive")
    surfaces = [row for row in descriptive if row.session.data["snapshot"]["bench"] == "surfaces"]
    operations = acceptance + [row for row in descriptive if row.session.data["snapshot"]["bench"] == "operations"]
    all_rows = operations + surfaces + calibration + threshold
    host_index = HostIndex(hosts, all_rows)
    hosts = host_index.specs
    tiers = _tier_order(metadata)
    pages = {
        "BENCHMARKS.md": render_root(hosts, sessions, host_index, operations, tiers),
        "benchmarks/history.md": render_history(hosts, host_index, operations, tiers, surfaces),
        "benchmarks/surfaces.md": render_surfaces(hosts, host_index, surfaces, tiers),
        "benchmarks/calibration.md": render_calibration(
            hosts, sessions, host_index, calibration, tiers),
        "benchmarks/thresholds.md": render_thresholds(
            hosts, sessions, host_index, threshold, tiers),
        "benchmarks/exceptions.md": render_exceptions(
            hosts, sessions, host_index),
        "benchmarks/competitors.md": render_competitors(hosts, competitors, tiers),
    }
    return {path: content.encode("utf-8") for path, content in pages.items()}


