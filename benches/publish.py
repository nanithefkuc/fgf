def render_exceptions(hosts: list[HostSpec], sessions: list[PublishedSession],
                      host_index: HostIndex) -> str:
    rows = []
    for session in sessions:
        data = session.data
        if not _is_exception_session(data):
            continue
        failed = _failed_cells_by_tier(data["decisions"])
        layout = data["layout_only"]
        for tier in sorted(failed):
            records = (layout.get("per_tier") or {}).get(tier) or {}
            for cell in failed[tier]:
                record = records.get(cell) or {}
                rows.append([
                    f"`{data['session_id']}`",
                    host_index.name(data["host"]["hostname"]),
                    tier,
                    f"`{cell}`",
                    f"`{data['arms']['candidate']['sha']}`",
                    fmt_ratio(record.get("failed_bound")),
                    fmt_ratio(record.get("spread")),
                    record.get("disposition", "-"),
                    record.get("owner_signature") or "-",
                ])
    lines = [
        "# Layout exceptions",
        "",
        "## Recorded exceptions",
        "",
        render_markdown_table(
            ["Session", "Host", "Tier", "Cell", "Library SHA",
             "Failed bound (log ratio)", "Spread (log ratio)", "Disposition",
             "Owner signature"], rows),
    ]
    lines += ["", "## Caveats", ""]
    lines += _exception_caveats(hosts)
    return "\n".join(lines).rstrip() + "\n"


