def _require_mapping(value: Any, where: str) -> dict:
    if not isinstance(value, dict):
        fail(f"{where} must be an object")
    return value


def _require_keys(mapping: dict, keys: Iterable[str], where: str) -> None:
    missing = [key for key in keys if key not in mapping]
    if missing:
        fail(f"{where} is missing {', '.join(missing)}")


def _require_string(value: Any, where: str, *, allow_empty: bool = False) -> str:
    if not isinstance(value, str) or (not value and not allow_empty):
        fail(f"{where} must be a non-empty string")
    return value


def _require_positive_int(value: Any, where: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        fail(f"{where} must be a positive integer")
    return value


def _require_positive_number(value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{where} must be a number")
    number = float(value)
    check_positive(number, where)
    return number


def _require_number(value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{where} must be a number")
    number = float(value)
    if not math.isfinite(number):
        fail(f"{where} must be finite, got {value!r}")
    return number


def _require_nonnegative_number(value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{where} must be a number")
    number = float(value)
    if not math.isfinite(number) or number < 0.0:
        fail(f"{where} must be finite and nonnegative, got {value!r}")
    return number


def _require_bool(value: Any, where: str) -> bool:
    if not isinstance(value, bool):
        fail(f"{where} must be a boolean")
    return value


def _validate_cell_row(row: dict, where: str, session: dict) -> None:
    _require_keys(row, ROW_KEYS, where)
    _require_string(row["host"], f"{where}.host")
    _require_string(row["tier"], f"{where}.tier")
    field = _require_string(row["field"], f"{where}.field")
    operation = _require_string(row["operation"], f"{where}.operation")
    prep = _require_string(row["prep"], f"{where}.prep")
    if prep not in ("prepared", "unprepared"):
        fail(f"{where}.prep must be prepared or unprepared")
    row_len = _require_positive_int(row["row_len"], f"{where}.row_len")
    rows = _require_positive_int(row["rows"], f"{where}.rows")
    sources = _require_positive_int(row["sources"], f"{where}.sources")
    alignment = _require_string(row["alignment"], f"{where}.alignment")
    if ALIGNMENT_RE.fullmatch(alignment) is None:
        fail(f"{where}.alignment must be aligned or offset{{k}}")
    cell = _require_string(row["cell"], f"{where}.cell")
    expected = f"{field}/{operation}/{prep}/{row_len}x{rows}x{sources}/{alignment}"
    if cell != expected:
        fail(f"{where}.cell {cell!r} does not match the key fields {expected!r}")
    arm = _require_string(row["arm"], f"{where}.arm")
    if arm not in ARM_ORDER:
        fail(f"{where}.arm must be one of {', '.join(ARM_ORDER)}")
    role = _require_string(row["role"], f"{where}.role")
    if role not in ROLE_ORDER:
        fail(f"{where}.role must be one of {', '.join(ROLE_ORDER)}")
    sha = _require_string(row["library_sha"], f"{where}.library_sha")
    session_id = _require_string(row["session_id"], f"{where}.session_id")
    if session_id != session["session_id"]:
        fail(f"{where}.session_id does not match the session")
    if arm in ("base", "candidate"):
        declared = session["arms"][arm]["sha"]
        if sha != declared:
            fail(f"{where}.library_sha does not match the {arm} arm")
    _require_bool(row["unstable"], f"{where}.unstable")
    _require_positive_number(row["summary_ns"], f"{where}.summary_ns")
    rounds = row["rounds_ns"]
    if not isinstance(rounds, list) or not rounds:
        fail(f"{where}.rounds_ns must be a non-empty list")
    for index, value in enumerate(rounds):
        _require_positive_number(value, f"{where}.rounds_ns[{index}]")
    if row["tier"] not in {tier["requested"] for tier in session["tiers"]}:
        fail(f"{where}.tier is not declared by the session")


def _decision_records(decisions: dict) -> list[tuple[str, dict]]:
    if not decisions:
        return []
    if "noninferiority" in decisions or "superiority" in decisions:
        return [("session", decisions)]
    return list(decisions.items())


def _failed_cells_by_tier(decisions: dict) -> dict[str, list[str]]:
    if not decisions:
        return {}
    if "noninferiority" in decisions:
        noninferiority = decisions.get("noninferiority") or {}
        per_tier = noninferiority.get("per_tier")
        if per_tier is None:
            per_tier = (decisions.get("per_tier") or {})
            per_tier = {
                tier: (record.get("noninferiority") or {})
                for tier, record in per_tier.items()
            }
        failed = {}
        for tier, record in per_tier.items():
            if record.get("passed") is False:
                failed[tier] = list(record.get("failed_cells") or [])
        return failed
    failed = {}
    for tier, record in decisions.items():
        noninferiority = record.get("noninferiority") or {}
        if noninferiority.get("passed") is False:
            failed[tier] = list(noninferiority.get("failed_cells") or [])
    return failed


def _layout_exception_covered(session: dict) -> bool:
    layout = session.get("layout_only")
    if not isinstance(layout, dict) or layout.get("asserted") is not True:
        return False
    failed = _failed_cells_by_tier(session.get("decisions") or {})
    if not failed:
        return False
    per_tier = layout.get("per_tier") or {}
    for tier, cells in failed.items():
        if not cells:
            return False
        records = per_tier.get(tier) or {}
        for cell in cells:
            record = records.get(cell)
            if not isinstance(record, dict):
                return False
            if record.get("disposition") not in (
                    "owner_exception_required", "regression_exceeds_spread"):
                return False
    return True


def _is_exception_session(session: dict) -> bool:
    return bool(_failed_cells_by_tier(session.get("decisions") or {})) \
        and session.get("layout_only") is not None


def _check_decisions(decisions: dict, where: str, *,
                     allow_layout_exception: bool = False,
                     session: dict | None = None) -> None:
    failed = _failed_cells_by_tier(decisions)
    confirmed = (
        session is not None
        and session.get("method_version") in STAGED_METHODS
        and bool(failed)
        and all(
            cells and set(cells) == set(
                (session.get("confirmed_failures") or {}).get(tier, [])
            )
            for tier, cells in failed.items()
        )
    )
    if failed:
        if confirmed or (allow_layout_exception and session is not None
                         and _layout_exception_covered(session)):
            pass
        else:
            tiers = ", ".join(sorted(failed))
            fail(f"{where} noninferiority did not pass for {tiers}")
    for label, record in _decision_records(decisions):
        superiority = record.get("superiority")
        if (isinstance(superiority, dict)
                and superiority.get("declared") is True
                and superiority.get("passed") is not True):
            tier_records = superiority.get("per_tier", {label: superiority})
            if confirmed and all(
                not item.get("declared")
                or (item.get("targets") and not item.get("failed_targets"))
                for item in tier_records.values()
            ):
                continue
            fail(f"{where}.{label} superiority did not pass")


def _recomputed_drift(
    stage_runs: list[dict],
    drift_method: str,
    where: str,
    *,
    method_version: str,
    expected_arms: tuple[str, ...] = ("base", "candidate"),
) -> float:
    expected_set = set(expected_arms)
    samples: list[float] = []
    use_placements = method_version in PLACEMENT_METHODS
    for index, run in enumerate(stage_runs):
        run_where = f"{where}[{index}]"
        if use_placements:
            placements = run.get("placements")
            if not isinstance(placements, list) or not placements:
                fail(f"{run_where}.placements must be a non-empty list")
            for p_index, stratum in enumerate(placements):
                stratum_obj = _require_mapping(
                    stratum, f"{run_where}.placements[{p_index}]"
                )
                stratum_controls = _require_mapping(
                    stratum_obj.get("controls"),
                    f"{run_where}.placements[{p_index}].controls",
                )
                if set(stratum_controls) != expected_set:
                    fail(
                        f"{run_where}.placements[{p_index}].controls keys differ "
                        f"from expected arms {sorted(expected_set)}"
                    )
                for arm in expected_arms:
                    entry = _require_mapping(
                        stratum_controls[arm],
                        f"{run_where}.placements[{p_index}].controls.{arm}",
                    )
                    samples.append(
                        _require_positive_number(
                            entry.get("start_ns"),
                            f"{run_where}.placements[{p_index}].controls.{arm}.start_ns",
                        )
                    )
                    _require_positive_number(
                        entry.get("end_ns"),
                        f"{run_where}.placements[{p_index}].controls.{arm}.end_ns",
                    )
        else:
            if run.get("placements") is not None:
                fail(f"{run_where}.placements is not allowed for {method_version}")
            controls = _require_mapping(
                run.get("controls"), f"{run_where}.controls"
            )
            if set(controls) != expected_set:
                fail(
                    f"{run_where}.controls keys differ from expected arms "
                    f"{sorted(expected_set)}"
                )
            for arm in expected_arms:
                entry = _require_mapping(
                    controls[arm], f"{run_where}.controls.{arm}"
                )
                samples.append(
                    _require_positive_number(
                        entry.get("start_ns"),
                        f"{run_where}.controls.{arm}.start_ns",
                    )
                )
                _require_positive_number(
                    entry.get("end_ns"),
                    f"{run_where}.controls.{arm}.end_ns",
                )
    if not samples:
        fail(f"{where} has no start controls")
    stats = bench_pair.drift_stats(samples)
    if drift_method == "iqr_over_median":
        drift = stats["drift"]
    elif drift_method == "p90_minus_p10_over_median":
        median = stats["median"]
        drift = (stats["p90"] - stats["p10"]) / median if median and median > 0 else None
    else:
        fail(f"{where} has unsupported drift_method {drift_method!r}")
    if drift is None:
        fail(f"{where} has undefined start-control drift")
    return float(drift)


def _rows_equal(actual: list[dict], expected: list[dict], tol: float) -> bool:
    if len(actual) != len(expected):
        return False
    for got, exp in zip(actual, expected):
        if set(got) != set(exp):
            return False
        for key, exp_val in exp.items():
            got_val = got[key]
            if key == "summary_ns":
                if not math.isclose(float(got_val), float(exp_val), rel_tol=tol, abs_tol=tol):
                    return False
            elif key == "rounds_ns":
                if len(got_val) != len(exp_val) or not all(
                    math.isclose(float(a), float(b), rel_tol=tol, abs_tol=tol)
                    for a, b in zip(got_val, exp_val)
                ):
                    return False
            elif got_val != exp_val:
                return False
    return True


def _validate_staged_rows_and_drift(session: dict, where: str) -> None:
    tol = 1e-9
    runs = session["runs"]
    declared_tiers = [tier["requested"] for tier in session["tiers"]]
    declared_tier_set = set(declared_tiers)
    config_rounds = int(session["config"]["rounds"])
    config_runs = int(session["config"]["runs"])
    arm_summaries = session["arm_summaries"]

    # Reject stray runs on undeclared tiers (and non-main calibration runs),
    # and validate every run's evidence according to method_version.
    method_version = session["method_version"]
    for r_index, run in enumerate(runs):
        tier = run.get("tier")
        if tier not in declared_tier_set:
            fail(f"{where}.runs[{r_index}].tier {tier!r} is not declared by the session")
        if session["kind"] == "calibration" and run.get("stage", "main") != "main":
            fail(f"{where}.runs[{r_index}].stage must be 'main' for calibration")
        if method_version not in PLACEMENT_METHODS:
            if run.get("placements") is not None:
                fail(f"{where}.runs[{r_index}].placements is not allowed for {method_version}")
            for arm in ("base", "candidate"):
                arm_entry = _require_mapping(
                    (run.get("arms") or {}).get(arm),
                    f"{where}.runs[{r_index}].arms.{arm}",
                )
                cells_map = _require_mapping(
                    arm_entry.get("cells"),
                    f"{where}.runs[{r_index}].arms.{arm}.cells",
                )
                for cell, raw_cell in cells_map.items():
                    cell_entry = _require_mapping(
                        raw_cell,
                        f"{where}.runs[{r_index}].arms.{arm}.cells.{cell}",
                    )
                    run_rounds = cell_entry.get("rounds_ns")
                    if not isinstance(run_rounds, list) or len(run_rounds) != config_rounds:
                        fail(
                            f"{where}.runs[{r_index}].arms.{arm}.cells.{cell}.rounds_ns "
                            f"must contain exactly {config_rounds} rounds"
                        )
                    round_vals = [
                        _require_positive_number(
                            v,
                            f"{where}.runs[{r_index}].arms.{arm}.cells.{cell}.rounds_ns[{idx}]",
                        )
                        for idx, v in enumerate(run_rounds)
                    ]
                    recorded = _require_positive_number(
                        cell_entry.get("summary_ns"),
                        f"{where}.runs[{r_index}].arms.{arm}.cells.{cell}.summary_ns",
                    )
                    expected_med = bench_pair.run_arm_summary(round_vals)
                    if not math.isclose(recorded, expected_med, rel_tol=tol, abs_tol=tol):
                        fail(
                            f"{where}.runs[{r_index}].arms.{arm}.cells.{cell}.summary_ns "
                            "disagrees with its retained rounds_ns"
                        )

    main_cells_by_tier: dict[str, set[str]] = {}
    for tier in declared_tiers:
        main_runs = [
            run for run in runs
            if run.get("tier") == tier and run.get("stage", "main") == "main"
        ]
        if not main_runs:
            fail(f"{where}: tier {tier} has no main-stage runs")
        if session["kind"] == "calibration" or method_version in PLACEMENT_METHODS:
            if len(main_runs) != config_runs or any(
                run.get("run") != idx for idx, run in enumerate(main_runs)
            ):
                fail(
                    f"{where}: {session['kind']} tier {tier} must have ascending runs 0..{config_runs - 1}"
                )
        for arm in ("base", "candidate"):
            first_cells: set[str] | None = None
            for run in main_runs:
                arm_entry = _require_mapping(
                    (run.get("arms") or {}).get(arm),
                    f"{where}.runs[{run.get('run')}].arms.{arm}",
                )
                cells_map = _require_mapping(
                    arm_entry.get("cells"),
                    f"{where}.runs[{run.get('run')}].arms.{arm}.cells",
                )
                cell_set = set(cells_map)
                if not cell_set:
                    fail(f"{where}: tier {tier} arm {arm} has empty run cells")
                if first_cells is None:
                    first_cells = cell_set
                elif cell_set != first_cells:
                    fail(f"{where}: tier {tier} arm {arm} run cells vary across runs")
            assert first_cells is not None
            if tier not in main_cells_by_tier:
                main_cells_by_tier[tier] = first_cells
            elif main_cells_by_tier[tier] != first_cells:
                fail(f"{where}: tier {tier} base and candidate arms cover different cells")
            arm_tier_summaries = _require_mapping(
                _require_mapping(arm_summaries.get(arm), f"{where}.arm_summaries.{arm}").get(tier),
                f"{where}.arm_summaries.{arm}.{tier}",
            )
            if set(arm_tier_summaries) != first_cells:
                fail(f"{where}.arm_summaries.{arm}.{tier} cells disagree with retained runs")
            for cell in sorted(first_cells):
                summaries = [
                    _require_positive_number(
                        run["arms"][arm]["cells"][cell].get("summary_ns"),
                        f"{where}.runs[{run.get('run')}].arms.{arm}.cells.{cell}.summary_ns",
                    )
                    for run in main_runs
                ]
                recomputed = statistics.median(summaries)
                recorded_summary = _require_positive_number(
                    arm_tier_summaries[cell],
                    f"{where}.arm_summaries.{arm}.{tier}.{cell}",
                )
                if not math.isclose(recorded_summary, recomputed, rel_tol=tol, abs_tol=tol):
                    fail(
                        f"{where}.arm_summaries.{arm}.{tier}.{cell} disagrees with retained run summaries"
                    )

    for arm in ("base", "candidate"):
        arm_map = _require_mapping(arm_summaries.get(arm), f"{where}.arm_summaries.{arm}")
        if set(arm_map) != declared_tier_set:
            fail(f"{where}.arm_summaries.{arm} tiers disagree with declared tiers")

    # Recompute the entire rows table via bench_pair.build_rows so summary_ns,
    # rounds_ns, role, unstable, host, and library_sha are all verified together.
    order_cells = list((session.get("inventory") or {}).get("order") or [])
    all_main_cells = sorted({cell for cells in main_cells_by_tier.values() for cell in cells})
    if not order_cells:
        order_cells = all_main_cells
    unstable_entries = (session.get("unstable") or {}).get("entries") or {}
    expected_rows = bench_pair.build_rows(
        session, declared_tiers, order_cells, unstable_entries
    )
    if not _rows_equal(session["rows"], expected_rows, tol):
        fail(f"{where}.rows disagree with retained run summaries or row metadata")

    if session["kind"] != "calibration":
        cap = float(session["config"]["drift_cap"])
        for tier in declared_tiers:
            for stage in ("main", "confirmation"):
                stage_runs = [
                    run for run in runs
                    if run.get("tier") == tier and run.get("stage", "main") == stage
                ]
                if not stage_runs:
                    continue
                drift = _recomputed_drift(
                    stage_runs,
                    session["drift_method"],
                    f"{where} tier {tier} stage {stage}",
                    method_version=method_version,
                    expected_arms=("base", "candidate"),
                )
                if drift > cap:
                    fail(
                        f"{where}: tier {tier} stage {stage} start-control drift "
                        f"{drift:.6f} exceeds cap {cap:.6f}"
                    )
    else:
        # Validate calibration recommendations against retained runs and drift.
        calibration = _require_mapping(session.get("calibration"), f"{where}.calibration")
        rec_recorded = _require_mapping(
            calibration.get("recommendation"), f"{where}.calibration.recommendation"
        )
        ratios_by_tier = {}
        drift_by_tier = {}
        for tier in declared_tiers:
            stage_runs = [
                run for run in runs
                if run.get("tier") == tier and run.get("stage", "main") == "main"
            ]
            tier_drift = _recomputed_drift(
                stage_runs,
                session["drift_method"],
                f"{where} calibration tier {tier}",
                method_version=method_version,
                expected_arms=("base", "candidate"),
            )
            drift_by_tier[tier] = {"drift": tier_drift}
            ratios = bench_pair.session_tier_ratios(session, tier, "main")
            if not ratios:
                fail(f"{where}: calibration tier {tier} lacks paired ratios")
            ratios_by_tier[tier] = ratios
        safety_factor = float(
            rec_recorded.get(
                "drift_safety_factor",
                session["config"].get("drift_safety_factor", 1.25),
            )
        )
        prior_drift = float(calibration.get("prior_drift") or 0.0)
        recomputed_rec, _ = bench_pair.calibration_recommendation(
            ratios_by_tier,
            float(session["config"]["delta"]),
            drift_by_tier,
            drift_safety_factor=safety_factor,
            prior_drift=prior_drift,
            run_step=bench_pair.RUN_STRIDES.get(method_version, 1),
        )
        if rec_recorded.get("runs") != recomputed_rec.get("runs"):
            fail(f"{where}.calibration.recommendation.runs disagrees with retained runs")
        if method_version in PLACEMENT_METHODS or "prior_drift" in calibration:
            if not math.isclose(
                float(rec_recorded["drift_cap"]),
                float(recomputed_rec["drift_cap"]),
                rel_tol=tol,
                abs_tol=tol,
            ):
                fail(
                    f"{where}.calibration.recommendation.drift_cap "
                    f"disagrees with recomputed {recomputed_rec['drift_cap']}"
                )
        elif float(rec_recorded["drift_cap"]) + tol < float(recomputed_rec["drift_cap"]):
            # Legacy pre-prior_drift /4 and /5 captures could raise drift_cap from
            # earlier same-host calibration sessions without storing prior_drift.
            fail(
                f"{where}.calibration.recommendation.drift_cap is below recomputed "
                f"minimum {recomputed_rec['drift_cap']}"
            )
        recorded_per_tier = _require_mapping(
            rec_recorded.get("per_tier"),
            f"{where}.calibration.recommendation.per_tier",
        )
        if set(recorded_per_tier) != declared_tier_set:
            fail(f"{where}.calibration.recommendation.per_tier disagrees with declared tiers")
        for tier in declared_tiers:
            rec_tier = _require_mapping(
                recorded_per_tier[tier],
                f"{where}.calibration.recommendation.per_tier.{tier}",
            )
            exp_tier = recomputed_rec["per_tier"][tier]
            if rec_tier.get("runs") != exp_tier.get("runs"):
                fail(
                    f"{where}.calibration.recommendation.per_tier.{tier}.runs "
                    "disagrees with retained runs"
                )
            if sorted(rec_tier.get("unstable_cells") or []) != sorted(
                exp_tier.get("unstable_cells") or []
            ):
                fail(
                    f"{where}.calibration.recommendation.per_tier.{tier}.unstable_cells "
                    "disagrees with retained runs"
                )
            exp_max = exp_tier.get("max_bound")
            rec_max = rec_tier.get("max_bound")
            if (exp_max is None) != (rec_max is None) or (
                exp_max is not None
                and not math.isclose(float(rec_max), float(exp_max), rel_tol=tol, abs_tol=tol)
            ):
                fail(
                    f"{where}.calibration.recommendation.per_tier.{tier}.max_bound "
                    "disagrees with retained runs"
                )
            if "limit" not in rec_tier:
                fail(
                    f"{where}.calibration.recommendation.per_tier.{tier}.limit is required"
                )
            if not math.isclose(
                float(rec_tier["limit"]), float(exp_tier["limit"]), rel_tol=tol, abs_tol=tol
            ):
                fail(
                    f"{where}.calibration.recommendation.per_tier.{tier}.limit "
                    "disagrees with config.delta"
                )


def validate_session(session: dict, where: str) -> None:
    if isinstance(session, dict) and session.get("kind") == "descriptive":
        try:
            bench_baseline.validate_session(session)
        except (ValueError, KeyError, TypeError, bench_baseline.check_surfaces.CheckError) as error:
            fail(f"{where}: {error}")
        return
    _require_mapping(session, where)
    _require_keys(session, SESSION_KEYS, where)
    if session["method_version"] not in SUPPORTED_METHODS:
        fail(f"{where}.method_version must be one of {', '.join(SUPPORTED_METHODS)}")
    expected_drift = bench_pair.METHOD_DRIFT[session["method_version"]]
    if session["drift_method"] != expected_drift:
        fail(f"{where}.drift_method must be {expected_drift}")
    _require_string(session["session_id"], f"{where}.session_id")
    _require_string(session["created_utc"], f"{where}.created_utc")
    kind = _require_string(session["kind"], f"{where}.kind")
    if kind not in KINDS:
        fail(f"{where}.kind must be one of {', '.join(KINDS)}")
    if "acceptance" in session:
        acceptance = _require_bool(session["acceptance"], f"{where}.acceptance")
        if acceptance != (kind == "acceptance"):
            fail(f"{where}.acceptance disagrees with kind")
    if session.get("reused_calibration") is True:
        fail(f"{where}.reused_calibration is true")
    if session.get("rejected") is True:
        fail(f"{where} was rejected")

    host = _require_mapping(session["host"], f"{where}.host")
    _require_keys(host, HOST_KEYS, f"{where}.host")
    _require_string(host["hostname"], f"{where}.host.hostname")

    snapshot = _require_mapping(session["snapshot"], f"{where}.snapshot")
    _require_keys(snapshot, SNAPSHOT_KEYS, f"{where}.snapshot")
    rustflags = _require_string(snapshot["rustflags"], f"{where}.snapshot.rustflags",
                                allow_empty=True)
    for marker in ALIGNMENT_MARKERS:
        if marker not in rustflags:
            fail(f"{where}.snapshot.rustflags lacks the pinned {marker} flag")

    arms = _require_mapping(session["arms"], f"{where}.arms")
    _require_keys(arms, ("base", "candidate"), f"{where}.arms")
    for arm_name in ("base", "candidate"):
        arm = _require_mapping(arms[arm_name], f"{where}.arms.{arm_name}")
        _require_keys(arm, ARM_KEYS, f"{where}.arms.{arm_name}")
        _require_string(arm["kind"], f"{where}.arms.{arm_name}.kind")
        _require_string(arm["sha"], f"{where}.arms.{arm_name}.sha")

    config = _require_mapping(session["config"], f"{where}.config")
    _require_keys(config, CONFIG_KEYS, f"{where}.config")
    config_runs = _require_positive_int(config["runs"], f"{where}.config.runs")
    _require_positive_int(config["rounds"], f"{where}.config.rounds")
    if session["method_version"] in PLACEMENT_METHODS:
        expected_placement_method = PLACEMENT_METHODS[session["method_version"]]
        if config.get("placement_method") != expected_placement_method:
            fail(f"{where}.config has no matching placement method")
        if snapshot.get("placement_matches_snapshot") is not True:
            fail(f"{where}.snapshot has no matching placement module")
        run_stride = bench_pair.RUN_STRIDES[session["method_version"]]
        if config_runs < bench_pair.MIN_RUNS_FOR_BOUND:
            fail(
                f"{where}.config.runs must be at least "
                f"{bench_pair.MIN_RUNS_FOR_BOUND} for {session['method_version']}"
            )
        if config_runs % run_stride != 0:
            fail(
                f"{where}.config.runs must be a multiple of {run_stride} for "
                f"{session['method_version']}"
            )
    for key in ("delta", "gamma"):
        _require_positive_number(config[key], f"{where}.config.{key}")
    if config["drift_cap"] is None:
        if kind != "calibration":
            fail(f"{where}.config.drift_cap must be set outside calibration")
    else:
        _require_nonnegative_number(config["drift_cap"],
                                    f"{where}.config.drift_cap")
    for key in ("delta", "gamma"):
        if float(config[key]) != 0.03:
            fail(f"{where}.config.{key} must be 0.03")
    _require_bool(config["calibrated"], f"{where}.config.calibrated")

    tiers = session["tiers"]
    if not isinstance(tiers, list) or not tiers:
        fail(f"{where}.tiers must be a non-empty list")
    for index, tier in enumerate(tiers):
        item = _require_mapping(tier, f"{where}.tiers[{index}]")
        _require_keys(item, TIER_KEYS, f"{where}.tiers[{index}]")
        _require_string(item["requested"], f"{where}.tiers[{index}].requested")
        _require_string(item["reported"], f"{where}.tiers[{index}].reported")
        if item["reported"] != item["requested"]:
            fail(f"{where}.tiers[{index}] reported backend {item['reported']!r} "
                 f"for requested {item['requested']!r}")
        _require_mapping(item["field_backends"], f"{where}.tiers[{index}].field_backends")
        if not _require_bool(item["ok"], f"{where}.tiers[{index}].ok"):
            fail(f"{where}.tiers[{index}] was rejected")

    runs = session["runs"]
    if not isinstance(runs, list):
        fail(f"{where}.runs must be a list")
    for index, run in enumerate(runs):
        item = _require_mapping(run, f"{where}.runs[{index}]")
        _require_keys(item, RUN_KEYS, f"{where}.runs[{index}]")
        if session["method_version"] in STAGED_METHODS:
            if item.get("stage") not in ("main", "confirmation"):
                fail(f"{where}.runs[{index}].stage is invalid")
        if session["method_version"] in PLACEMENT_METHODS:
            expected_placement_method = PLACEMENT_METHODS[session["method_version"]]
            if config.get("placement_method") != expected_placement_method:
                fail(f"{where}.config has no matching placement method")
            if snapshot.get("placement_matches_snapshot") is not True:
                fail(f"{where}.snapshot has no matching placement module")
            try:
                bench_pair.placement.validate_run(
                    item,
                    int(config["rounds"]),
                    expected_arms=("base", "candidate"),
                    method=expected_placement_method,
                )
            except (ValueError, TypeError, KeyError) as error:
                fail(f"{where}.runs[{index}]: {error}")

    summaries = _require_mapping(session["arm_summaries"], f"{where}.arm_summaries")
    _require_keys(summaries, ("base", "candidate"), f"{where}.arm_summaries")

    rows = session["rows"]
    if not isinstance(rows, list):
        fail(f"{where}.rows must be a list")
    for index, row in enumerate(rows):
        _validate_cell_row(_require_mapping(row, f"{where}.rows[{index}]"),
                           f"{where}.rows[{index}]", session)

    if session.get("scope") is not None:
        scope = _require_mapping(session["scope"], f"{where}.scope")
        cells = scope.get("cells")
        if (not isinstance(cells, list) or not cells
                or not all(isinstance(cell, str) and cell for cell in cells)
                or len(set(cells)) != len(cells)
                or bench_baseline.digest(cells) != scope.get("digest")):
            fail(f"{where}.scope is empty, ambiguous, or has an invalid digest")
        if scope.get("kind") not in ("full", "selected"):
            fail(f"{where}.scope has an unknown kind")
        if scope["kind"] == "selected" and not scope.get("rationale"):
            fail(f"{where}.scope requires a selection rationale")
        inventory_order = session.get("inventory", {}).get("order", [])
        if [cell for cell in inventory_order if cell in set(cells)] != cells:
            fail(f"{where}.scope is outside the full inventory order")
        if scope["kind"] == "full" and cells != inventory_order:
            fail(f"{where}.scope claims full coverage but omits inventory cells")
        expected = {(tier["requested"], arm, cell)
                    for tier in tiers for arm in ("base", "candidate") for cell in cells}
        observed = [(row["tier"], row["arm"], row["cell"]) for row in rows]
        if len(observed) != len(expected) or set(observed) != expected:
            fail(f"{where}.rows do not exactly cover scope, tiers, and arms")
    unstable = session.get("unstable")
    if unstable is not None:
        unstable = _require_mapping(unstable, f"{where}.unstable")
        entries = _require_mapping(
            unstable.get("entries"), f"{where}.unstable.entries"
        )
        for tier, cells in entries.items():
            tier_where = f"{where}.unstable.entries.{tier}"
            _require_string(tier, tier_where, allow_empty=True)
            if not isinstance(cells, list) or not all(
                isinstance(cell, str) for cell in cells
            ):
                fail(f"{tier_where} must be a list of cell ids")

    decisions = _require_mapping(session["decisions"], f"{where}.decisions")
    if decisions:
        if "noninferiority" in decisions or "superiority" in decisions:
            for key in ("noninferiority", "superiority"):
                record = _require_mapping(
                    decisions.get(key), f"{where}.decisions.{key}"
                )
                per_tier = record.get("per_tier")
                if per_tier is None:
                    continue
                per_tier = _require_mapping(
                    per_tier, f"{where}.decisions.{key}.per_tier"
                )
                for tier, tier_record in per_tier.items():
                    tier_where = f"{where}.decisions.{key}.per_tier.{tier}"
                    tier_record = _require_mapping(tier_record, tier_where)
                    excluded = tier_record.get("excluded_unstable")
                    if excluded is not None:
                        _require_mapping(
                            excluded, f"{tier_where}.excluded_unstable"
                        )
                    if key == "superiority":
                        per_target = tier_record.get("per_target")
                        if per_target is not None:
                            per_target = _require_mapping(
                                per_target, f"{tier_where}.per_target"
                            )
                            for cell, target in per_target.items():
                                target_where = f"{tier_where}.per_target.{cell}"
                                target = _require_mapping(target, target_where)
                                if "unstable" in target:
                                    _require_bool(
                                        target["unstable"],
                                        f"{target_where}.unstable",
                                    )
        else:
            for tier, tier_decision in decisions.items():
                _require_string(tier, f"{where}.decisions.{tier}",
                                allow_empty=True)
                record = _require_mapping(tier_decision,
                                          f"{where}.decisions.{tier}")
                noninferiority = _require_mapping(
                    record.get("noninferiority"),
                    f"{where}.decisions.{tier}.noninferiority")
                for key in ("excluded_unstable",):
                    excluded = noninferiority.get(key)
                    if excluded is not None:
                        _require_mapping(excluded, f"{where}.decisions.{tier}.noninferiority.{key}")
                if record.get("superiority") is not None:
                    superiority = _require_mapping(
                        record["superiority"],
                        f"{where}.decisions.{tier}.superiority")
                    excluded = superiority.get("excluded_unstable")
                    if excluded is not None:
                        _require_mapping(excluded, f"{where}.decisions.{tier}.superiority.excluded_unstable")
    if session["method_version"] in STAGED_METHODS:
        _validate_staged_rows_and_drift(session, where)
        if config.get("confirmation") is not (kind != "calibration"):
            fail(f"{where}.config.confirmation disagrees with kind")
        if kind != "calibration":
            targets = (
                (session.get("threshold") or {}).get("target_set")
                if kind == "threshold" else
                (config.get("targets_declaration") or {}).get("cells")
            )
            try:
                recomputed = {
                    tier["requested"]: bench_pair.recorded_staged_decision(
                        session, tier["requested"], targets
                    )
                    for tier in tiers
                }
            except (ValueError, KeyError, TypeError) as error:
                fail(f"{where}: {error}")
            if decisions != bench_pair.publishable_decisions(recomputed):
                fail(f"{where}.decisions disagree with staged runs")
            if session.get("confirmed_failures") != {
                tier: record["confirmed_failures"] for tier, record in recomputed.items()
            }:
                fail(f"{where}.confirmed_failures disagree with staged runs")
    # A completed threshold comparison records evidence even when its candidate
    # is not superior; measurement rejection and staged-run validation still apply.
    if kind != "threshold":
        _check_decisions(decisions, f"{where}.decisions",
                         allow_layout_exception=True, session=session)
    rejections = session["rejections"]
    if not isinstance(rejections, list):
        fail(f"{where}.rejections must be a list")
    if rejections:
        fail(f"{where} records rejected measurements")

    if kind == "calibration":
        calibration = _require_mapping(session.get("calibration"),
                                       f"{where}.calibration")
        _require_keys(calibration, CALIBRATION_KEYS, f"{where}.calibration")
        mode = _require_string(calibration["mode"], f"{where}.calibration.mode")
        if mode not in ("base_vs_base", "base_vs_layout_control"):
            fail(f"{where}.calibration.mode is unsupported")
        recommendation = _require_mapping(
            calibration["recommendation"], f"{where}.calibration.recommendation")
        _require_keys(recommendation, RECOMMENDATION_KEYS,
                      f"{where}.calibration.recommendation")
        if recommendation["runs"] is not None:
            _require_positive_int(
                recommendation["runs"],
                f"{where}.calibration.recommendation.runs")
        _require_nonnegative_number(
            recommendation["drift_cap"],
            f"{where}.calibration.recommendation.drift_cap")
        per_tier = _require_mapping(
            recommendation["per_tier"],
            f"{where}.calibration.recommendation.per_tier")
        for tier, tier_record in per_tier.items():
            tier_where = f"{where}.calibration.recommendation.per_tier.{tier}"
            _require_string(tier, tier_where, allow_empty=True)
            record = _require_mapping(tier_record, tier_where)
            if record.get("runs") is not None:
                _require_positive_int(record["runs"], f"{tier_where}.runs")
            if "limit" in record:
                _require_nonnegative_number(record["limit"],
                                            f"{tier_where}.limit")
            if record.get("max_bound") is not None:
                _require_nonnegative_number(record["max_bound"],
                                            f"{tier_where}.max_bound")
            unstable = record.get("unstable_cells")
            if unstable is not None:
                if not isinstance(unstable, list) or not all(
                    isinstance(cell, str) for cell in unstable
                ):
                    fail(f"{tier_where}.unstable_cells must be a list of cell ids")
    if kind == "threshold":
        threshold = _require_mapping(session.get("threshold"),
                                     f"{where}.threshold")
        _require_keys(threshold, THRESHOLD_KEYS, f"{where}.threshold")
        _require_string(threshold["item_key"], f"{where}.threshold.item_key")
        _require_nonnegative_number(threshold["old"],
                                    f"{where}.threshold.old")
        _require_nonnegative_number(threshold["new"],
                                    f"{where}.threshold.new")
        unit = _require_string(threshold["unit"], f"{where}.threshold.unit")
        if unit not in UNITS:
            fail(f"{where}.threshold.unit is unsupported")
        if threshold.get("axis") is not None:
            _require_string(threshold["axis"], f"{where}.threshold.axis")
        comparison = threshold["comparison"]
        if not isinstance(comparison, str) or comparison not in {"<", "<=", "=="}:
            fail(f"{where}.threshold.comparison has no supported source predicate")
        derived_targets = set()
        cells = threshold["cells"]
        if not isinstance(cells, list) or not cells:
            fail(f"{where}.threshold.cells must be a non-empty list")
        for index, entry in enumerate(cells):
            entry = _require_mapping(entry, f"{where}.threshold.cells[{index}]")
            _require_string(entry.get("cell"), f"{where}.threshold.cells[{index}].cell")
            axis = _require_nonnegative_number(
                entry.get("axis_value"), f"{where}.threshold.cells[{index}].axis_value"
            )
            if bench_pair.threshold_route_differs(
                axis, threshold["old"], threshold["new"], comparison
            ):
                derived_targets.add(entry["cell"])
        targets = threshold["target_set"]
        if not isinstance(targets, list):
            fail(f"{where}.threshold.target_set must be a list")
        for index, cell in enumerate(targets):
            _require_string(cell, f"{where}.threshold.target_set[{index}]")
        if not derived_targets or set(targets) != derived_targets:
            fail(f"{where}.threshold.target_set disagrees with its source predicate")

    if "layout_only" in session and session["layout_only"] is not None:
        layout = _require_mapping(session["layout_only"], f"{where}.layout_only")
        _require_keys(layout, ("asserted", "per_tier"), f"{where}.layout_only")
        _require_bool(layout["asserted"], f"{where}.layout_only.asserted")
        per_tier = _require_mapping(layout["per_tier"],
                                    f"{where}.layout_only.per_tier")
        for tier, cells in per_tier.items():
            tier_where = f"{where}.layout_only.per_tier.{tier}"
            _require_string(tier, tier_where, allow_empty=True)
            entries = _require_mapping(cells, tier_where)
            for cell, disposition in entries.items():
                cell_where = f"{tier_where}.{cell}"
                record = _require_mapping(disposition, cell_where)
                _require_keys(record, ("failed_bound", "spread", "disposition"),
                              cell_where)
                _require_number(record["failed_bound"],
                                f"{cell_where}.failed_bound")
                if record["spread"] is not None:
                    _require_number(record["spread"], f"{cell_where}.spread")
                disposition_name = _require_string(
                    record["disposition"], f"{cell_where}.disposition")
                signature = record.get("owner_signature")
                if signature is not None:
                    _require_string(signature, f"{cell_where}.owner_signature")
        tol = 1e-9
        failed_by_tier = _failed_cells_by_tier(decisions)
        if session["method_version"] in PLACEMENT_METHODS:
            if failed_by_tier and "remeasured" not in layout:
                fail(f"{where}.layout_only.remeasured is required for failed tiers")
        if session["method_version"] in STAGED_METHODS and "remeasured" in layout:
            remeasured_map = _require_mapping(
                layout["remeasured"], f"{where}.layout_only.remeasured"
            )
            if session["method_version"] in PLACEMENT_METHODS and failed_by_tier:
                if set(remeasured_map) != set(failed_by_tier):
                    fail(
                        f"{where}.layout_only.remeasured tiers disagree with failed tiers"
                    )
            for tier, rem in remeasured_map.items():
                rem_where = f"{where}.layout_only.remeasured.{tier}"
                rem_obj = _require_mapping(rem, rem_where)
                placements = rem_obj.get("placements")
                if not isinstance(placements, list) or not placements:
                    fail(f"{rem_where}.placements must be a non-empty list")
                if session["method_version"] in PLACEMENT_METHODS:
                    expected_placement_method = PLACEMENT_METHODS[session["method_version"]]
                    if any(
                        not isinstance(p, dict) or p.get("run") != idx
                        for idx, p in enumerate(placements)
                    ):
                        fail(
                            f"{rem_where}.placements must have ascending run ids "
                            f"0..{len(placements) - 1}"
                        )
                    expected_failed = set(failed_by_tier.get(tier, ()))
                    for p_index, p_run in enumerate(placements):
                        try:
                            bench_pair.placement.validate_run(
                                _require_mapping(p_run, f"{rem_where}.placements[{p_index}]"),
                                int(config["rounds"]),
                                expected_arms=("base", "layout_control"),
                                expected_cells=expected_failed if expected_failed else None,
                                method=expected_placement_method,
                            )
                        except (ValueError, TypeError, KeyError) as error:
                            fail(f"{rem_where}.placements[{p_index}]: {error}")
                    if kind != "calibration":
                        cap = float(config["drift_cap"])
                        drift = _recomputed_drift(
                            placements,
                            session["drift_method"],
                            rem_where,
                            method_version=session["method_version"],
                            expected_arms=("base", "layout_control"),
                        )
                        if drift > cap:
                            fail(
                                f"{rem_where}: start-control drift {drift:.6f} exceeds cap {cap:.6f}"
                            )
                    if expected_failed:
                        if len(placements) != int(config["runs"]):
                            fail(
                                f"{rem_where}.placements must contain exactly "
                                f"{int(config['runs'])} runs"
                            )
                        base_runs = [
                            {
                                cell: entry["summary_ns"]
                                for cell, entry in p["arms"]["base"]["cells"].items()
                            }
                            for p in placements
                        ]
                        layout_runs = [
                            {
                                cell: entry["summary_ns"]
                                for cell, entry in p["arms"]["layout_control"]["cells"].items()
                            }
                            for p in placements
                        ]
                        ratios = bench_pair.paired_log_ratios(
                            base_runs, layout_runs, sorted(expected_failed)
                        )
                        tier_entries = _require_mapping(
                            per_tier.get(tier), f"{where}.layout_only.per_tier.{tier}"
                        )
                        decision_cells = (
                            (decisions.get("per_tier") or {})
                            .get(tier, {})
                            .get("noninferiority", {})
                            .get("per_cell", {})
                        )
                        for cell in sorted(expected_failed):
                            cell_where = f"{where}.layout_only.per_tier.{tier}.{cell}"
                            record = _require_mapping(tier_entries.get(cell), cell_where)
                            recomputed_bound = bench_pair.hl_upper_bound(ratios[cell])[
                                "upper_bound"
                            ]
                            if "remeasured_bound" not in record:
                                fail(f"{cell_where}.remeasured_bound is required")
                            rec_rem = _require_number(
                                record["remeasured_bound"],
                                f"{cell_where}.remeasured_bound",
                            )
                            if not math.isclose(
                                rec_rem, recomputed_bound, rel_tol=tol, abs_tol=tol
                            ):
                                fail(
                                    f"{cell_where}.remeasured_bound disagrees with placements"
                                )
                            if cell in decision_cells and "upper_bound" in decision_cells[cell]:
                                expected_failed_bound = float(
                                    decision_cells[cell]["upper_bound"]
                                )
                                if not math.isclose(
                                    float(record["failed_bound"]),
                                    expected_failed_bound,
                                    rel_tol=tol,
                                    abs_tol=tol,
                                ):
                                    fail(
                                        f"{cell_where}.failed_bound disagrees with decisions"
                                    )
                            spread = record["spread"]
                            if spread is None:
                                fail(f"{cell_where}.spread is missing for remeasured cell")
                            if "calibration_spread" not in record:
                                fail(f"{cell_where}.calibration_spread is required")
                            cal_spread = _require_number(
                                record["calibration_spread"],
                                f"{cell_where}.calibration_spread",
                            )
                            expected_spread = max(cal_spread, recomputed_bound)
                            if not math.isclose(
                                float(spread), expected_spread, rel_tol=tol, abs_tol=tol
                            ):
                                fail(
                                    f"{cell_where}.spread disagrees with calibration and remeasured bounds"
                                )
                            expected_disp = bench_pair.layout_disposition(
                                float(record["failed_bound"]), float(spread)
                            )["disposition"]
                            if record["disposition"] != expected_disp:
                                fail(
                                    f"{cell_where}.disposition disagrees with layout_disposition"
                                )
                elif session["method_version"] in STAGED_METHODS and kind != "calibration":
                    cap = float(config["drift_cap"])
                    drift = _recomputed_drift(
                        placements,
                        session["drift_method"],
                        rem_where,
                        method_version=session["method_version"],
                        expected_arms=("base", "layout_control"),
                    )
                    if drift > cap:
                        fail(
                            f"{rem_where}: start-control drift {drift:.6f} exceeds cap {cap:.6f}"
                        )


