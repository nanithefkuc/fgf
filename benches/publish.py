def render_history(hosts: list[HostSpec], host_index: HostIndex,
                   rows: list[PublishedRow], tiers: list[str],
                   surfaces: list[PublishedRow] | None = None) -> str:
    history = _ordered_rows(rows, host_index, tiers, history=True)
