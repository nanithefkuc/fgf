#!/usr/bin/env python3
"""Publish the fgf measurement record from committed paired sessions.

    python3 benches/publish.py [--manifest PATH] [--records PATH]
                               [--output PATH] [--verify]

``benchmarks/sessions.json`` is the committed manifest. It fixes the host
display order, marks unavailable hosts, and lists every published
``session.json`` below ``bench-records/`` with the SHA-256 digest of the file.
The publisher validates each session against the paired-run schema, renders
``BENCHMARKS.md`` and ``benchmarks/*.md`` in memory, and writes them below the
output root.

Every measurement row is keyed by ``{host}/{tier}/{cell id}``. A refresh
appends rows in manifest order; the latest row for an anchor is current.
Accepted rows publish the candidate arm; base-vs-base and layout-control
sessions are labelled ``baseline`` and ``layout_control``. Calibration and
threshold-evidence rows are published in separate tables.

The optional ``competitors`` list names captured ``bench-comp`` logs below
``bench-records/``. Each log is parsed for the harnesses' structured ``TRIO``,
``PRIME``, and ``RESULT`` records and rendered on
``benchmarks/competitors.md``.

``--verify`` regenerates everything in memory and fails when a manifest digest
or a generated byte differs from the file on disk. It never writes.
"""

