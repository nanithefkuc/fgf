"""Behavioral tests for `api/kernel_registry.py` over synthetic documents.

Every test builds minimal rustdoc-JSON documents shaped like the format
the pinned `API_NIGHTLY` emits (verified against the generated inventory
cells), so the suite exercises the checker's behavior without compiling
anything. No environment variables are required.
"""

from __future__ import annotations

