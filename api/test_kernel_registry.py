class Audit(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.registry = fresh_registry(*base_fixture())
        cls.tiers = {entry["entry"]: entry["tier"] for entry in cls.registry["entries"]}

    def log(self, lines: list[str]) -> str:
        return "\n".join(lines) + "\n"

    def path_of(self, local: str) -> str:
        matches = [path for path in self.tiers if path.endswith(local)]
        self.assertEqual(len(matches), 1, local)
        return matches[0]

    def audit(self, floor: str, actual: str, lines: list[str]) -> list[str]:
        return kernel_registry.audit(self.registry, floor, actual, self.log(lines))

    def marker(self, local: str) -> str:
        path = self.path_of(local)
        return f"kernel_differential executed tier={self.tiers[path]} entry={path}"

    def test_complete_run_passes(self) -> None:
        lines = [self.marker(local) for local in (
            "mul_ssse3_v2", "xor_v1", "mul_avx2_v3", "mul_gfni_crypto", "mul_v4", "mul_v4x",
        )]
        self.assertEqual(self.audit("v4x", "v4x", lines), [])
        self.assertEqual(self.audit("v3_gfni_crypto", "v3_gfni_crypto", lines[:4]), [])

    def test_downgrade_run_passes_and_requires_the_ceiling_only(self) -> None:
        lines = [self.marker(local) for local in ("mul_ssse3_v2", "xor_v1", "mul_avx2_v3")]
        self.assertEqual(self.audit("v4x", "v3", lines), [])

    def test_ceiling_above_floor_may_execute_additional_registered_entries(self) -> None:
        required = ("mul_ssse3_v2", "xor_v1", "mul_avx2_v3")
        self.assertEqual(self.audit("v3", "v4x", [self.marker(name) for name in required]), [])
        self.assertEqual(self.audit("v3", "v4x", [
            self.marker(name) for name in (*required, "mul_gfni_crypto", "mul_v4", "mul_v4x")
        ]), [])

    def test_missing_required_entry_fails(self) -> None:
        lines = [self.marker(local) for local in ("mul_ssse3_v2", "xor_v1", "mul_avx2_v3")]
        errors = self.audit("v4x", "v4x", lines)
        self.assertTrue(all("missing executed marker" in line for line in errors))
        for local in ("mul_gfni_crypto", "mul_v4", "mul_v4x"):
            self.assertTrue(any(local in line for line in errors), errors)

    def test_floor_cannot_be_satisfied_by_a_weaker_request(self) -> None:
        lines = [self.marker(local) for local in ("mul_ssse3_v2", "xor_v1")]
        errors = self.audit("v3", "v3", lines)
        self.assertTrue(any("mul_avx2_v3" in line for line in errors))
        self.assertTrue(all("missing executed marker" in line for line in errors))

    def test_unknown_entry_fails(self) -> None:
        errors = self.audit(
            "v4x",
            "v4x",
            ["kernel_differential executed tier=v4x entry=fgf::kernel::x86::gf8::rogue"],
        )
        self.assertEqual(sum("unknown entry" in line for line in errors), 1)
        self.assertIn("rogue", "".join(errors))

    def test_wrong_tier_fails(self) -> None:
        path = self.path_of("mul_v4x")
        errors = self.audit(
            "v4x", "v4x", [f"kernel_differential executed tier=v3 entry={path}"]
        )
        self.assertEqual(sum("registry says v4x" in line for line in errors), 1)
        # The wrong-tier marker does not satisfy the requirement either.
        self.assertTrue(any("missing executed marker" in line for line in errors))

    def test_over_request_marker_fails(self) -> None:
        lines = [self.marker(local) for local in ("mul_ssse3_v2", "xor_v1", "mul_avx2_v3", "mul_v4x")]
        errors = self.audit("v4x", "v3", lines)
        self.assertTrue(any("above the request ceiling v3" in line for line in errors))
        self.assertFalse(any("missing executed marker" in line for line in errors))

    def test_scalar_request_rejects_every_marker(self) -> None:
        errors = self.audit("v4x", "scalar", [self.marker("mul_ssse3_v2")])
        self.assertEqual(len(errors), 1)
        self.assertIn("above the request ceiling scalar", errors[0])

    def test_audited_non_entry_marker_fails(self) -> None:
        errors = self.audit(
            "v4x",
            "v4x",
            [
                "kernel_differential executed tier=v2 "
                "entry=fgf::kernel::x86::gf8::avx2::multiply_vectors_avx2"
            ],
        )
        self.assertTrue(any("audited non-entry" in line for line in errors))

    def test_corrupt_and_unrelated_lines_are_handled(self) -> None:
        lines = [
            self.marker("mul_ssse3_v2"),
            self.marker("xor_v1"),
            "kernel_differential executing tier=v2 case=old_style",
            "kernel_differential executed tier=notatier entry=fgf::kernel::x86::gf8::mul_ssse3_v2",
            "test result: ok",
            self.marker("mul_ssse3_v2"),  # duplicate receipt is fine
        ]
        errors = self.audit("v2", "v2", lines)
        self.assertEqual(len(errors), 1)
        self.assertIn("unknown tier notatier", errors[0])

    def test_unknown_floor_or_actual_fails_closed(self) -> None:
        with self.assertRaises(kernel_registry.RegistryError):
            kernel_registry.audit(self.registry, "v4", "v4x", "")
        with self.assertRaises(kernel_registry.RegistryError):
            kernel_registry.audit(self.registry, "v4x", "v1", "")

    def test_registry_with_an_invalid_entry_tier_fails(self) -> None:
        broken = dict(self.registry)
        broken["entries"] = [{"entry": "fgf::kernel::x86::gf8::mul", "tier": "v9", "token": "X"}]
        with self.assertRaises(kernel_registry.RegistryError) as ctx:
            kernel_registry.audit(broken, "v4x", "v4x", "")
        self.assertIn("no valid tier", fragment(ctx.exception))


class CommandLine(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.out = Path(self.tmp.name)

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def run_cli(self, *args: str, env_extra: dict[str, str] | None = None) -> subprocess.CompletedProcess:
        import os

        env = {k: v for k, v in os.environ.items() if k not in ("API_NIGHTLY", "API_FORMAT")}
        env["API_NIGHTLY"] = CHANNEL
        env["API_FORMAT"] = FORMAT
        if env_extra:
            env.update(env_extra)
        return subprocess.run(
            [sys.executable, str(SCRIPT), *args],
            capture_output=True,
            text=True,
            cwd=HERE.parent,
            env=env,
        )

    def write_docs(self, public: dict, private: dict) -> tuple[Path, Path]:
        public_path = self.out / "public.json"
        private_path = self.out / "private.json"
        public_path.write_text(json.dumps(public))
        private_path.write_text(json.dumps(private))
        return public_path, private_path

    def test_generate_writes_the_registry_and_reports_counts(self) -> None:
        public_path, private_path = self.write_docs(*base_fixture())
        registry_path = self.out / "registry.json"
        result = self.run_cli(
            "generate",
            "--public-doc", str(public_path),
            "--private-doc", str(private_path),
            "--format", FORMAT,
            "--channel", CHANNEL,
            "--target", TARGET,
            "--features", FEATURES,
            "--out", str(registry_path),
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("6 entries", result.stdout)
        self.assertIn("4 audited tokenless", result.stdout)
        registry = json.loads(registry_path.read_text())
        self.assertEqual(len(registry["entries"]), 6)
        self.assertIn("identity", registry)

    def test_generate_fails_with_violation_list(self) -> None:
        fixture = Fixture()
        fn_id = fixture.add_fn(
            ["fgf", "kernel", "x86", "gf8", "ssse3", "mul"], [resolved_type("crate::field::Elem", "e")]
        )
        fixture.family("gf8", [fn_id])
        public_path, private_path = self.write_docs(*fixture.seal())
        result = self.run_cli(
            "generate",
            "--public-doc", str(public_path),
            "--private-doc", str(private_path),
            "--format", FORMAT,
            "--channel", CHANNEL,
            "--target", TARGET,
            "--out", str(self.out / "registry.json"),
        )
        self.assertEqual(result.returncode, 1)
        self.assertIn("unmapped first parameter", result.stderr)

    def test_check_identity_fails_on_a_stale_artifact(self) -> None:
        public_path, private_path = self.write_docs(*base_fixture())
        registry_path = self.out / "registry.json"
        self.assertEqual(
            self.run_cli(
                "generate",
                "--public-doc", str(public_path),
                "--private-doc", str(private_path),
                "--format", FORMAT,
                "--channel", CHANNEL,
                "--target", TARGET,
                "--out", str(registry_path),
            ).returncode,
            0,
        )
        ok = self.run_cli("check-identity", str(registry_path), "--target", TARGET)
        self.assertEqual(ok.returncode, 0, ok.stderr)
        registry = json.loads(registry_path.read_text())
        registry["identity"]["features"] = "default"
        registry_path.write_text(json.dumps(registry))
        stale = self.run_cli("check-identity", str(registry_path), "--target", TARGET)
        self.assertEqual(stale.returncode, 1)
        self.assertIn("stale", stale.stderr)
        self.assertIn("features", stale.stderr)

    def test_audit_subcommand_end_to_end(self) -> None:
        public_path, private_path = self.write_docs(*base_fixture())
        registry_path = self.out / "registry.json"
        self.run_cli(
            "generate",
            "--public-doc", str(public_path),
            "--private-doc", str(private_path),
            "--format", FORMAT,
            "--channel", CHANNEL,
            "--target", TARGET,
            "--out", str(registry_path),
        )
        registry = json.loads(registry_path.read_text())
        lines = [
            f"kernel_differential executed tier={entry['tier']} entry={entry['entry']}"
            for entry in registry["entries"]
        ]
        log = self.out / "test.log"
        log.write_text("\n".join(lines) + "\n")
        ok = self.run_cli(
            "audit", str(registry_path), "--floor", "v4x", "--actual", "v4x", "--log", str(log)
        )
        self.assertEqual(ok.returncode, 0, ok.stderr)
        log.write_text("\n".join(lines[:1]) + "\n")
        missing = self.run_cli(
            "audit", str(registry_path), "--floor", "v4x", "--actual", "v4x", "--log", str(log)
        )
        self.assertEqual(missing.returncode, 1)
        self.assertIn("missing executed marker", missing.stderr)


