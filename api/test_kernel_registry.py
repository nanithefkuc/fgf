import sys
import tempfile
import unittest
from copy import deepcopy
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "kernel_registry.py"
sys.path.insert(0, str(HERE))

import kernel_registry  # noqa: E402

FORMAT = "61"
CHANNEL = "nightly-test"
TARGET = "x86_64-unknown-linux-gnu"
FEATURES = "all-features"


def token_type(name: str) -> dict:
    return {"resolved_path": {"path": f"archmage::{name}", "id": f"tok-{name}", "args": None}}


def resolved_type(path: str, ref: str) -> dict:
    return {"resolved_path": {"path": path, "id": ref, "args": None}}


def fn_entry(name: str, params: list[dict], visibility: str = "public") -> dict:
    inputs = [[f"p{i}", param] for i, param in enumerate(params)]
    return {
        "name": name,
        "visibility": visibility,
        "inner": {
            "function": {
                "sig": {"inputs": inputs, "output": None, "is_c_variadic": False},
                "generics": {"params": [], "where_predicates": []},
                "header": {"is_const": False, "is_unsafe": False, "is_async": False, "abi": "Rust"},
                "has_body": True,
            }
        },
    }


def generic_fn_entry(name: str, params: list[dict], generic_names: list[str]) -> dict:
    entry = fn_entry(name, params)
    entry["inner"]["function"]["generics"]["params"] = [
        {"name": name_, "kind": {"type": {"default": None}}} for name_ in generic_names
    ]
    return entry


def module_entry(items: list[str], visibility: str = "public") -> dict:
    return {"name": None, "visibility": visibility, "inner": {"module": {"items": items}}}


def use_entry(name: str, target: str | None, is_glob: bool = False) -> dict:
    return {
        "name": name,
        "visibility": "public",
        "inner": {"use": {"name": name, "is_glob": is_glob, "id": target, "source": name}},
    }


def make_doc(index: dict[str, dict], paths: dict[str, list[str]]) -> dict:
    definitions = {key: {"path": segments, "kind": "function"} for key, segments in paths.items()}
    for entry in index.values():
        function = entry.get("inner", {}).get("function")
        if function:
            for _, parameter in function["sig"]["inputs"]:
                resolved = parameter.get("resolved_path")
                if resolved:
                    definitions.setdefault(str(resolved["id"]), {
                        "path": resolved["path"].split("::"), "kind": "struct",
                    })
    return {
        "format_version": int(FORMAT),
        "index": index,
        "paths": definitions,
    }


class Fixture:
    """A synthetic crate: `fgf::internals` glob-re-exports a pub(crate)
    `fgf::kernel::x86` module holding one family subtree per mapped tier.

    `x86_modules` maps module name to (id, [fn ids]); call `fn_id` fields
    are generated by the constructor.
    """

    def __init__(self) -> None:
        self.index: dict[str, dict] = {}
        self.paths: dict[str, list[str]] = {}
        self.next_id = 0
        self.internals_id = self.add(
            "module", module_entry([]), ["fgf", "internals"], "module"
        )
        self.x86_id = self.add("module", module_entry([]), None, "module")

    def add(self, kind_hint: str, entry: dict, path: list[str] | None, path_kind: str) -> str:
        self.next_id += 1
        item_id = str(self.next_id)
        self.index[item_id] = entry
        if path is not None:
            self.paths[item_id] = path
        return item_id

    def add_fn(
        self,
        definition: list[str],
        params: list[dict],
        visibility: str = "public",
        generic_names: list[str] | None = None,
    ) -> str:
        name = definition[-1]
        entry = (
            generic_fn_entry(name, params, generic_names)
            if generic_names
            else fn_entry(name, params, visibility)
        )
        if generic_names is None:
            entry["visibility"] = visibility
        return self.add("function", entry, definition, "function")

    def attach(self, parent_id: str, child_id: str) -> None:
        self.index[parent_id]["inner"]["module"]["items"].append(child_id)

    def family(self, name: str, fn_ids: list[str]) -> str:
        family_id = self.add(
            "module", module_entry(fn_ids), ["fgf", "kernel", "x86", name], "module"
        )
        self.attach(self.x86_id, family_id)
        return family_id

    def attach_fn(self, family_name: str, fn_id: str) -> None:
        family_id = next(
            item
            for item in self.index[self.x86_id]["inner"]["module"]["items"]
            if self.paths.get(item, [None])[-1:] == [family_name]
        )
        self.index[family_id]["inner"]["module"]["items"].append(fn_id)

    def seal(self, with_helper: bool = False) -> tuple[dict, dict]:
        """Return (public, private) documents. With `with_helper`, the
        private document alone gains a pub(crate) token-first helper under
        `kernel::x86::gf8::avx2`, unreachable through the facade, to
        exercise the private pass."""
        glob = self.add("use", use_entry("x86", self.x86_id, is_glob=True), None, "use")
        self.attach(self.internals_id, glob)
        public = make_doc(deepcopy(self.index), deepcopy(self.paths))
        index, paths = deepcopy(self.index), deepcopy(self.paths)
        if with_helper:
            helper_id = str(max(int(k) for k in index) + 1)
            index[helper_id] = fn_entry(
                "hidden_helper_v2", [token_type("X64V2Token")], visibility="crate"
            )
            paths[helper_id] = ["fgf", "kernel", "x86", "gf8", "avx2", "hidden_helper_v2"]
            avx2_id = str(int(helper_id) + 1)
            index[avx2_id] = module_entry([helper_id], visibility="crate")
            paths[avx2_id] = ["fgf", "kernel", "x86", "gf8", "avx2"]
            gf8 = next(
                item
                for item in index[self.x86_id]["inner"]["module"]["items"]
                if paths.get(item, [None])[-1:] == ["gf8"]
            )
            index[gf8]["inner"]["module"]["items"].append(avx2_id)
        private = make_doc(index, paths)
        return public, private


def base_fixture() -> tuple[dict, dict]:
    """One entry per mapped family plus the four audited tokenless
    functions, all reachable through the facade."""
    fixture = Fixture()
    return _populate_fixture(fixture).seal()


def base_fixture_with_helper() -> tuple[dict, dict]:
    """`base_fixture` plus a pub(crate) token-first helper in the private
    document alone."""
    fixture = Fixture()
    _populate_fixture(fixture)
    return fixture.seal(with_helper=True)


def _populate_fixture(fixture: Fixture) -> Fixture:
    fn_ids: list[str] = []
    cases = [
        (["fgf", "kernel", "x86", "gf8", "ssse3", "mul_ssse3_v2"], token_type("X64V2Token")),
        (["fgf", "kernel", "x86", "gf8", "avx2", "mul_avx2_v3"], token_type("X64V3Token")),
        (
            ["fgf", "kernel", "x86", "gf16", "gfni", "single", "mul_gfni_crypto"],
            token_type("X64V3GfniCryptoToken"),
        ),
        (["fgf", "kernel", "x86", "gf8", "avx512", "single", "mul_v4"], token_type("X64V4Token")),
        (["fgf", "kernel", "x86", "gf8", "avx512", "wide", "mul_v4x"], token_type("X64V4xToken")),
        (["fgf", "kernel", "x86", "bytes", "sse2", "xor_v1"], token_type("X64V1Token")),
    ]
    for definition, params in cases:
        fn_ids.append(fixture.add_fn(definition, [params]))
    fixture.family("gf8", fn_ids[:1] + fn_ids[3:])
    fixture.family("gf16", fn_ids[2:3])
    fixture.family("gf32", fn_ids[1:2])
    fixture.family("bytes", fn_ids[5:6])
    for name in ("multiply_vectors_avx2", "multiply_vectors_ssse3", "gf32_tiles", "gf64_tiles"):
        fixture.add_fn(
            ["fgf", "kernel", "x86", "gf8", "avx2", name],
            [resolved_type("__m256i", "intrin"), resolved_type("__m256i", "intrin")],
        )
    return fixture


def fresh_registry(public: dict, private: dict, **overrides) -> dict:
    with tempfile.TemporaryDirectory(prefix="kr-test-") as directory:
        root = Path(directory)
        (root / "src").mkdir()
        (root / "tests").mkdir()
        (root / "Cargo.toml").write_text("[package]\n")
        (root / "api").mkdir()
        shutil.copy(SCRIPT, root / "api" / "kernel_registry.py")
        kwargs = dict(
            channel=CHANNEL,
            fmt=FORMAT,
            target=TARGET,
            features=FEATURES,
            private_allowlist=frozenset(),
            root=root,
        )
        kwargs.update(overrides)
        return kernel_registry.generate(public, private, **kwargs)


def fragment(exc: Exception) -> str:
    return str(exc)


class TokenMapping(unittest.TestCase):
    def test_each_token_maps_to_its_family(self) -> None:
        registry = fresh_registry(*base_fixture())
        tiers = {entry["entry"]: entry["tier"] for entry in registry["entries"]}
        self.assertEqual(tiers["fgf::kernel::x86::gf8::ssse3::mul_ssse3_v2"], "v2")
        self.assertEqual(tiers["fgf::kernel::x86::bytes::sse2::xor_v1"], "v2")
        self.assertEqual(tiers["fgf::kernel::x86::gf8::avx2::mul_avx2_v3"], "v3")
        self.assertEqual(
            tiers["fgf::kernel::x86::gf16::gfni::single::mul_gfni_crypto"], "v3_gfni_crypto"
        )
        self.assertEqual(tiers["fgf::kernel::x86::gf8::avx512::single::mul_v4"], "v4x")
        self.assertEqual(tiers["fgf::kernel::x86::gf8::avx512::wide::mul_v4x"], "v4x")

    def test_generic_function_is_one_entry_with_token_tier(self) -> None:
        fixture = _populate_fixture(Fixture())
        fn_id = fixture.add_fn(
            ["fgf", "kernel", "x86", "gf8", "gfni", "single", "mul_generic"],
            [token_type("X64V3Token")],
            generic_names=["NATIVE", "M"],
        )
        fixture.attach_fn("gf8", fn_id)
        registry = fresh_registry(*fixture.seal())
        entries = {entry["entry"]: entry for entry in registry["entries"]}
        self.assertEqual(len(entries), 7)
        self.assertEqual(entries["fgf::kernel::x86::gf8::gfni::single::mul_generic"]["tier"], "v3")
        self.assertEqual(
            entries["fgf::kernel::x86::gf8::gfni::single::mul_generic"]["token"], "X64V3Token"
        )


class GenerationFailures(unittest.TestCase):
    def one_entry_fixture(self, params: list[dict]) -> tuple[dict, dict]:
        fixture = Fixture()
        fn_id = fixture.add_fn(["fgf", "kernel", "x86", "gf8", "ssse3", "mul"], params)
        fixture.family("gf8", [fn_id])
        return fixture.seal()

    def full_families(self, public: dict, private: dict, **overrides) -> None:
        """Regenerate with the failing function added to an otherwise
        complete fixture, so the only error is the one under test."""
        with self.assertRaises(kernel_registry.RegistryError) as ctx:
            fresh_registry(public, private, **overrides)
        return fragment(ctx.exception)

    def test_unmapped_resolved_first_parameter_fails(self) -> None:
        public, private = self.one_entry_fixture(
            [resolved_type("crate::field::Elem", "elem")]
        )
        message = self.full_families(public, private)
        self.assertIn("unmapped first parameter `crate::field::Elem`", message)
        self.assertIn("mul", message)

    def test_primitive_first_parameter_fails(self) -> None:
        public, private = self.one_entry_fixture([{"primitive": "u8"}])
        self.assertIn("unmapped primitive", self.full_families(public, private))

    def test_generic_first_parameter_fails(self) -> None:
        public, private = self.one_entry_fixture([{"generic": "T"}])
        message = self.full_families(public, private)
        self.assertIn("generic first parameter `T`", message)
        self.assertIn("concrete capability token", message)

    def test_local_type_with_a_token_name_is_not_an_archmage_proof(self) -> None:
        public, private = self.one_entry_fixture(
            [resolved_type("fgf::X64V3Token", "local-token")]
        )
        self.assertIn("unmapped first parameter", self.full_families(public, private))

    def test_parameterless_function_fails(self) -> None:
        public, private = self.one_entry_fixture([])
        message = self.full_families(public, private)
        self.assertIn("parameterless", message)
        self.assertIn("mul", message)

    def test_missing_family_fails(self) -> None:
        fixture = Fixture()
        fn_id = fixture.add_fn(
            ["fgf", "kernel", "x86", "gf8", "ssse3", "mul"], [token_type("X64V2Token")]
        )
        fixture.family("gf8", [fn_id])
        message = self.full_families(*fixture.seal())
        for family in ("v3", "v3_gfni_crypto", "v4x"):
            self.assertIn(f"no registry entry for token family {family}", message)
        self.assertNotIn("no registry entry for token family v2", message)


